#!/usr/bin/env python3
"""tools/data/facades_src.json (attributes read from Street View, see streetview.py) -> src/campuses/marin/facades.js,
the per-building table town.js consumes instead of random skins. Colours become linear-ish [r, g, b] 0..255 sRGB triples.
Usage: python facades.py"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
src = json.load(open(os.path.join(HERE, 'data', 'facades_src.json')))
def rgb(h): return [int(h[1:3], 16), int(h[3:5], 16), int(h[5:7], 16)] if isinstance(h, str) and len(h) == 7 and h[0] == '#' else None
out = {}
for k, v in sorted(src['buildings'].items()):
    if v.get('visible') == 'no' and not v.get('lv') and not v.get('col'): continue
    e = dict(kind=v.get('kind'), lv=v.get('lv'), wall=v.get('wall'), col=rgb(v.get('col')), trim=rgb(v.get('trim')), roof=v.get('roof'), roofMat=v.get('roofMat'), roofCol=rgb(v.get('roofCol')),
             garage=bool(v.get('garage')), porch=bool(v.get('porch')), conf=v.get('conf'))
    sf = v.get('storefront')
    if sf: e['store'] = dict(glass=sf.get('glass'), awning=rgb(sf.get('awning')), sign=sf.get('sign'), signBg=rgb(sf.get('signBg')), signFg=rgb(sf.get('signFg')))
    y = v.get('yard') or {}
    if y.get('fence') and y['fence'] != 'none': e['fence'] = y['fence']
    if y.get('hedge'): e['hedge'] = y['hedge']
    if y.get('driveway'): e['drive'] = True
    tr = [t['type'] + ('!' if t.get('big') else '') for t in v.get('trees') or []]
    if tr: e['trees'] = tr
    out[k] = {a: b for a, b in e.items() if b not in (None, False)}
js = ('// GENERATED by tools/facades.py from tools/data/facades_src.json: what each building around the campus really looks like,\n'
      '// read from Google Street View (storeys seen from the street, wall material / colour, roof type / colour, storefront,\n'
      '// awning, sign text, fences, hedges, trees). Keys are OSM way ids. Do not edit by hand.\n'
      'export const FACADES = ' + json.dumps(out, separators=(',', ':'), ensure_ascii=False) + ';\n')
open(os.path.join(HERE, '..', 'facades.js'), 'w').write(js)
print('facades.js', len(out), 'buildings', len(js), 'bytes')
