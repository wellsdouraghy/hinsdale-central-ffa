#!/usr/bin/env python3
"""Earl of March: split the school's one OSM footprint into roof blocks (needs numpy shapely pillow + dem.py).

OSM has the whole school as ONE polygon (12 650 m2); the lidar surface shows six roof levels inside it. The zones are
rectangles in the building's own frame (u along its long walls, 43.3 deg off east; v across), read off a 3 m table of
(DSM - ground) printed by this script, and cut out of the OSM outline. Every piece's top is then MEASURED again from
the lidar inside it (median = deck; p92 = parapets, plant and solar arrays) and printed next to the 3D-tiles height.
Writes src/campuses/earlofmarch/blocks.js (rings noded where two blocks meet, so the builder can tell an outside wall
from a step between two roofs edge by edge).   Usage: python blocks.py [debug.png]
"""
import json, math, os, sys
import numpy as np
from shapely.geometry import Polygon, box as sbox, Point, LineString, MultiPolygon
from shapely.ops import unary_union, polygonize
from shapely import affinity
import dem
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
D = json.load(open(os.path.join(ROOT, 'public/campuses/earlofmarch/campus.json')))
Y0 = 93.66; DTM = dem.lidar('dtm'); DSM = dem.lidar('dsm')
ringOf = lambda i: [b for b in D['buildings'] if b['id'] == i][0]['outer'][0]
SITES = [dict(key='SCHOOL', ids=[68609482], cx=84.0, cz=16.0, deg=-43.26, zones='school_zones.json', rest=dict(name='old', kind='old')),
         dict(key='CIVIC', ids=[69099636, 576122574], cx=10.0, cz=170.0, deg=27.4, zones='civic_zones.json', rest=dict(name='rest', kind='lib1'))]
def noded(g, others):
    pts = list(g.exterior.coords)[:-1]; out = []
    for i in range(len(pts)):
        a, b = pts[i], pts[(i + 1) % len(pts)]; seg = LineString([a, b]); extra = []
        for o in others:
            for q in list(o.exterior.coords)[:-1]:
                if seg.distance(Point(q)) < 0.02 and Point(q).distance(Point(a)) > 0.05 and Point(q).distance(Point(b)) > 0.05: extra.append((seg.project(Point(q)), q))
        out.append(a); last = None
        for d, q in sorted(extra):
            if last is None or d - last > 0.05: out.append(q); last = d
    return out
js = '// Earl of March: the school footprint (OSM way 68609482) and the Mlacak Centre + library (69099636, 576122574) split into roof blocks:\n// generated by tools/blocks.py, do not edit by hand. deck = lidar roof level above y = 0 (m), ring = outline (x east, z south), noded where two blocks meet.\n'
ALL = {}
for S in SITES:
    P = unary_union([Polygon(ringOf(i)).buffer(0.03) for i in S['ids']]).buffer(-0.03).simplify(0.02) if len(S['ids']) > 1 else Polygon(ringOf(S['ids'][0]))
    if P.geom_type != 'Polygon': P = max(P.geoms, key=lambda g: g.area)
    TH = math.radians(S['deg']); UX, UZ = math.cos(TH), math.sin(TH); CX, CZ = S['cx'], S['cz']
    W = lambda u, v: (CX + u * UX - v * UZ, CZ + u * UZ + v * UX)
    rect = lambda u0, v0, u1, v1: Polygon([W(u0, v0), W(u1, v0), W(u1, v1), W(u0, v1)])
    ZONES = json.load(open(os.path.join(HERE, 'data', S['zones'])))
    pieces = []; rest = P
    for z in ZONES[::-1]:
        r = rect(*z['uv']).intersection(rest)
        if r.is_empty: continue
        rest = rest.difference(rect(*z['uv']))
        for g in (r.geoms if hasattr(r, 'geoms') else [r]):
            if g.geom_type == 'Polygon' and g.area > 6: pieces.append((z, g))
    for g in (rest.geoms if hasattr(rest, 'geoms') else [rest]):
        if g.geom_type == 'Polygon' and g.area > 6: pieces.append((S['rest'], g))
    blocks = []
    for z, g in pieces:
        g = g.simplify(0.05); others = [h for _, h in pieces if h is not g and h.distance(g) < 0.05]
        r = noded(g, others); core = g.buffer(-1.2)
        if core.is_empty: core = g
        minx, minz, maxx, maxz = core.bounds; XX, ZZ = np.meshgrid(np.arange(minx, maxx, 1.0), np.arange(minz, maxz, 1.0)); m = np.array([[core.contains(Point(x, zz)) for x, zz in zip(rx, rz)] for rx, rz in zip(XX, ZZ)])
        a = DSM.at(XX[m], ZZ[m]) - Y0; rr = g.buffer(1.2).exterior; n = max(8, int(rr.length / 1.5)); rp = [rr.interpolate(k / n, normalized=True).coords[0] for k in range(n)]; gr = DTM.at([p[0] for p in rp], [p[1] for p in rp]) - Y0
        blocks.append(dict(name=z['name'], kind=z['kind'], deck=round(float(np.percentile(a, z.get('q', 50))), 2), p92=round(float(np.percentile(a, 92)), 2), area=round(g.area), ring=[[round(p[0], 2), round(p[1], 2)] for p in r]))
        print('%-6s %-9s %-6s area %5d  deck %.2f  p92 %.2f  ground near %.2f..%.2f  vertices %d' % (S['key'], z['name'], z['kind'], g.area, blocks[-1]['deck'], blocks[-1]['p92'], gr.min(), gr.max(), len(r)))
    blocks.sort(key=lambda b: -b['area']); ALL[S['key']] = blocks
    print(S['key'], 'pieces', len(blocks), 'area', sum(b['area'] for b in blocks), 'of', round(P.area))
    js += 'export const %s_FRAME = %s;\n' % (S['key'], json.dumps(dict(cx=CX, cz=CZ, ang=round(TH, 5))))
    js += 'export const %s_RING = %s;\n' % (S['key'], json.dumps([[round(p[0], 2), round(p[1], 2)] for p in list(P.exterior.coords)[:-1]]))
    js += 'export const %s_BLOCKS = [\n' % S['key'] + ',\n'.join('  ' + json.dumps(b, separators=(',', ':')) for b in blocks) + ',\n];\n'
open(os.path.join(HERE, '..', 'blocks.js'), 'w').write(js)
blocks = ALL['SCHOOL'] + ALL['CIVIC']
if len(sys.argv) > 1:
    from PIL import Image, ImageDraw
    im = Image.open(os.path.join(ROOT, 'public/campuses/earlofmarch/satellite.jpg')); x0, z0, x1, z1 = -70, -90, 190, 240; sc = 4
    c = im.crop((int((x0 + 360) * 4), int((z0 + 330) * 4), int((x1 + 360) * 4), int((z1 + 330) * 4))).resize(((x1 - x0) * sc, (z1 - z0) * sc)); d = ImageDraw.Draw(c); Q = lambda p: ((p[0] - x0) * sc, (p[1] - z0) * sc)
    for b in blocks:
        d.line([Q(p) for p in b['ring'] + b['ring'][:1]], fill=(255, 255, 0), width=2); cx = sum(p[0] for p in b['ring']) / len(b['ring']); cz = sum(p[1] for p in b['ring']) / len(b['ring']); d.text(Q((cx - 6, cz)), '%s %.1f' % (b['name'], b['deck']), fill=(255, 255, 255))
        for i, p in enumerate(b['ring']): d.text(Q(p), str(i), fill=(0, 255, 255))
    c.save(sys.argv[1])
